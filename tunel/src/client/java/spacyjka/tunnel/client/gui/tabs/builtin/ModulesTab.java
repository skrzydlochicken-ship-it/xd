package spacyjka.tunnel.client.gui.tabs.builtin;

import spacyjka.tunnel.client.gui.GuiTheme;
import spacyjka.tunnel.client.gui.GuiThemes;
import spacyjka.tunnel.client.gui.tabs.Tab;
import spacyjka.tunnel.client.gui.tabs.TabScreen;
import net.minecraft.client.gui.screens.Screen;

public class ModulesTab extends Tab {
    public ModulesTab() {
        super("Modules");
    }

    @Override
    public TabScreen createScreen(GuiTheme theme) {
        return theme.modulesScreen();
    }

    @Override
    public boolean isScreen(Screen screen) {
        return GuiThemes.get().isModulesScreen(screen);
    }
}
